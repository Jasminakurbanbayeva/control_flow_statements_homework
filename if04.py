def main(a,b,c):
    """
    Find number of positive numbers there are in the given numbers.
    Args:
        a: integer
        b: integer
        c: integer
    returns:
        integer: the number of positive numbers in the given numbers
    """
    if a > 0:
        return a
    elif b > 0:
        return b
    elif c > 0:
        return c
print(main(9,1,4))
        